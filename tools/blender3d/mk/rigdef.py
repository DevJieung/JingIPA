FOOT_L = REST["footL"]


def _foot(side: str, leg_deg: float):
    """발이 볼 방향. 기본은 **월드 기준 고정**(발바닥이 늘 수평)이고,
    `RIGID_FOOT` 면 다리가 돈 만큼 같이 돈다(발목이 없는 것과 같다)."""
    rest = FOOT_R if side == "R" else FOOT_L
    return rot_x(rest, leg_deg) if RIGID_FOOT else rest


