#: ★ ablation 손잡이 — `B3D_RIGID_FOOT=1` 이면 발을 **정강이에 그대로 붙여** 굴린다.
#:   후보 A 의 강체 막대(발목 없음)를 그대로 흉내 내는 것이고, 「발목 뼈가 몇 px 을
#:   벌어 주는가」를 재려고 둔다. 기본은 꺼짐.
RIGID_FOOT = os.environ.get("B3D_RIGID_FOOT", "") not in ("", "0")


def _n(v):
    l = math.sqrt(sum(c * c for c in v)) or 1.0
    return (v[0] / l, v[1] / l, v[2] / l)


def rot_x(v, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return (v[0], v[1] * c - v[2] * s, v[1] * s + v[2] * c)


def rot_z(v, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return (v[0] * c - v[1] * s, v[0] * s + v[1] * c, v[2])


def lerp(a, b, t):
    return tuple(x + (y - x) * t for x, y in zip(a, b))


REST = {n: _n((t[0] - h[0], t[1] - h[1], t[2] - h[2]))
        for (n, h, t, _p, _c) in BONES}
LEN = {n: math.dist(h, t) for (n, h, t, _p, _c) in BONES}

#: ★★ **발은 언제나 이 방향을 본다.** 정강이가 어떻게 기울든 `aim()` 이 세계
#:   기준으로 겨누므로, 이 한 줄이 「발바닥이 늘 땅과 나란하다」의 전부다.
#:   A 가 못 한 것이 이것이고, 그래서 A 의 walk 는 발이 3px 떴다.
