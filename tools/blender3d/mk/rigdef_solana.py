RAMP_STOPS = (0.0, 0.40, 0.86)

# ---------------------------------------------------------------- 자세 도우미
#: ★ 회전축이 요쿨과 다르다. 요쿨은 월드 X 로 굽혔지만(`rot_x`), 여기서는 **화면
#:   평면 안에서** 굽혀야 한다 — 그 축이 깊이축 `d` 다.
_AX_D = V(0, 1, 0)          # 깊이축 (화면 평면 안에서 도는 축)
_AX_A = V(1, 0, 0)          # 가로축 (깊이 쪽으로 도는 축)
_AX_Z = (0.0, 0.0, 1.0)


def rot_axis(v, k, deg):
    """로드리게스. `k` 를 축으로 `v` 를 `deg` 만큼 돌린다 (둘 다 아마추어 좌표)."""
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    kx = (k[1] * v[2] - k[2] * v[1], k[2] * v[0] - k[0] * v[2], k[0] * v[1] - k[1] * v[0])
    kd = _dot(k, v) * (1.0 - c)
    return (v[0] * c + kx[0] * s + k[0] * kd,
            v[1] * c + kx[1] * s + k[1] * kd,
            v[2] * c + kx[2] * s + k[2] * kd)


def pitch(v, deg):
    """화면 평면 안에서 돌린다. **+ 는 시계 방향**(위 → 오른쪽 → 아래)."""
    return rot_axis(v, _AX_D, deg)


def lean(v, deg):
    """깊이 쪽으로 기울인다 (+ 는 카메라 쪽으로)."""
    return rot_axis(v, _AX_A, deg)


def twist(v, deg):
    """제자리에서 비튼다."""
    return rot_axis(v, _AX_Z, deg)


REST = {n: _unit(_sub(t, h)) for (n, h, t, _p, _c) in BONES}
LEN = {n: math.dist(h, t) for (n, h, t, _p, _c) in BONES}


def _arms(s, grip=GRIP):
    """활 팔 · 시위 팔을 한 번에 — 자세마다 이 한 줄이면 손이 시위에 붙는다."""
    bu, bf, bh, _w, _e = _bow_arm(grip)
    du, df, dh, _w2, _e2 = _draw_arm(s)
    return {"armL": V(*bu), "foreL": V(*bf), "handL": V(*bh),
            "armR": V(*du), "foreR": V(*df), "handR": V(*dh),
            "_scale": {"nock": (1.0, s, 1.0)}}


# ---------------------------------------------------------------- idle 6칸
def pose_idle(i: int, n: int = 6) -> dict:
    """숨쉬기. 다리가 없으므로 **발밑이 산수로 고정**된다 — 요쿨이 발목 뼈로 푼
    숙제가 여기서는 아예 안 생긴다."""
    p = 2 * math.pi * i / n
    br = math.sin(p)
    sw = math.sin(p + 1.2)
    g = _add(GRIP, (0, 0, 1), 0.012 * br)          # 활이 숨결만큼 오르내린다
    d = _arms(BRACE, g)
    d.update({
        "chest": pitch(REST["chest"], 1.6 * br),
        "head":  pitch(REST["head"], -1.4 * br),
        "crown": pitch(REST["crown"], 2.2 * br),
        "skirt": pitch(REST["skirt"], 0.9 * sw),
        "train": pitch(REST["train"], 3.4 * sw),
        "bow":   pitch(REST["bow"], 1.1 * br),
    })
    return d


# ---------------------------------------------------------------- walk 8칸
def pose_walk(i: int, n: int = 8) -> dict:
    """걷기. ★★ **다리가 한 짝도 없다** — 원화의 드레스가 바닥까지 내려온다.
    그래서 걸음을 치마의 좌우 기울임 · 자락의 휘두름 · 몸통의 비틀림으로만 낸다.
    ☆ 요쿨의 걷기가 「무릎을 굽히면 발이 뜬다」와 싸운 자리인데, 여기서는 그 싸움이
      통째로 없어지고 대신 **걷는 것처럼 보이게 하는 것**이 어려운 일이 됐다.
    """
    p = 2 * math.pi * i / n
    s, c = math.sin(p), math.cos(p)
    g = _add(GRIP, (0, 0, 1), 0.02 * c)
    d = _arms(BRACE, g)
    d.update({
        "hips":  twist(REST["hips"], 4.0 * s),
        "chest": pitch(lean(REST["chest"], 2.2 * s), 1.4 + 1.6 * c),
        "head":  pitch(REST["head"], -1.2 * c),
        "crown": pitch(REST["crown"], 3.0 * c),
        # 치마는 **걸음과 반대로** 늦게 따라온다 — 그 지연이 「천」으로 읽힌다
        "skirt": lean(pitch(REST["skirt"], 3.2 * math.sin(p - 0.7)),
                      2.6 * math.sin(p - 0.7)),
        "train": pitch(lean(REST["train"], 5.0 * math.sin(p - 1.1)),
                       7.0 * math.sin(p - 1.1)),
        "bow":   pitch(REST["bow"], 2.0 * c),
    })
    return d


