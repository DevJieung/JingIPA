"""솔라나(활 · 불) — **뼈 · 재질 · 자세 표**. bpy 를 안 쓴다(숫자만 든다).

요쿨(`rigdef.py`)과 같은 계약을 지키지만 **숫자는 한 줄도 안 겹친다.**
둘째 캐릭터를 만들면서 「무엇이 공짜이고 무엇이 새 일인가」를 가른 자리가 여기다.

## 요쿨과 통째로 다른 것 넷
1. ★★ **다리가 없다.** 드레스가 바닥까지 내려와 발이 한 톨도 안 보인다
   (`art/units/solana.png` 실측: 76~100줄이 전부 치맛자락이다). 그래서 요쿨이
   제일 비싸게 푼 숙제 11번(발목 뼈 · 발밑 흔들림)이 **통째로 사라졌다** —
   `thighR/shinR/footR` 여섯 뼈와 `_foot()` 도우미가 없다.
   ☆ 대신 걷기를 **다리로 못 그린다.** 치마 흔들림 · 자락 휘두름 · 몸통 기울임으로
     낸다(`pose_walk`). 로어가 그것을 허락한다 — 「드레스 자락이 늘 타고 있어도
     걸음이 흐트러지지 않는다」.
2. ★★ **두 손이 서로 다른 일을 한다.** 검은 한 손이 들고 한 손은 논다. 활은
   **활 손이 버티고 시위 손이 당긴다** — 그래서 팔을 각도로 못 짠다. 시위 매듭이
   어디 있느냐가 먼저 정해지고 손이 거기로 **따라가야** 하므로 `_ik2()`(두 뼈
   역운동학)를 새로 넣었다. 각도로 짜면 칸마다 손이 시위에서 몇 px 씩 떨어진다.
3. ★★ **시위가 늘었다 줄었다 한다.** 강체 뼈 부착에서 그것은 **뼈 크기**로만 난다.
   그래서 `core.make_action` 에 `_scale` 키를 넣었다(요쿨은 안 쓰므로 결과가
   한 픽셀도 안 바뀐다). `nock` 뼈의 y 크기가 곧 당김 깊이다.
4. ★★ **화면 좌표계로 짠다**(`P()`). 요쿨은 「-Y 가 앞」이라는 몸 기준으로 짰는데,
   활잡이는 **몸이 카메라를 보고 화살만 화면 오른쪽으로** 날아가야 한다(원화가
   정확히 그렇다). 그래서 좌표를 `(a, d, z)` 로 바꿨다 —
     **a = 화면 가로(오른쪽 +) · d = 깊이(멀어지는 쪽 +) · z = 화면 위**
   이고, 게임 방향 SE(yaw 45)에서 `world_x == a` · `world_y == d` 로 **정확히**
   떨어진다(산수로 확인했다). 원화의 픽셀 좌표를 그대로 옮겨 적을 수 있다.
   ☆ 화면 세로는 `0.2419·(d-a) + 0.9397·z` 다 — 오른쪽으로 갈수록 내려간다.

## 원화에서 옮긴 자 (art/units/solana.png · 77x101 · 발바닥 y=100 · 가로 가운데 x=36)
    1 px = 0.0228 m   ·   a = (x-36)·0.0228   ·   z = (100-y)·0.0228
      관 꼭대기 y=4   → z 2.19      턱 y=30      → z 1.60
      어깨 y=34       → z 1.50      허리 y=52    → z 1.09
      불붙은 자락 y=78 → z 0.50     활 손잡이 x=58,y=38 → a 0.50, z 1.41
"""
import math

# ---------------------------------------------------------------- 화면 좌표계
_R = math.sqrt(0.5)


def P(a, d, z):
    """화면 좌표 (a=가로, d=깊이, z=세로) → 아마추어 좌표.

    ★ yaw 45(게임 방향 SE)에서 `world_x == a`, `world_y == d` 가 **정확히** 성립한다.
      그래서 원화를 픽셀로 재서 그대로 옮겨 적을 수 있고, 8방향은 이 축을 돌린
      결과로 저절로 나온다.
    """
    return (_R * (a + d), _R * (d - a), z)


def V(a, d, z):
    """방향 벡터도 같은 변환(회전이라 길이가 안 변한다)."""
    return P(a, d, z)


# ---------------------------------------------------------------- 활의 자
#: 화살이 날아가는 쪽. 수평에서 **14도 아래** — 게임의 표적이 바닥을 걷기 때문이고,
#: 원화의 활도 그만큼 뒤로 누워 있다.
_TH = math.radians(14.0)
DIR = (math.cos(_TH), 0.0, -math.sin(_TH))          # 화살 방향 (화면 좌표)
BUP = (math.sin(_TH), 0.0, math.cos(_TH))           # 활채가 서는 쪽 (화살에 수직)

GRIP = (0.42, 0.00, 1.36)                           # 활 손잡이
#: ★★ **활채 반높이는 검사 11번(8방향 키 일관성)이 정한다.** 이 캐릭터에서 제일
#:   비싸게 배운 자리다 — 아래 「활과 관의 예산」을 봐라.
BOW_H = 0.55                                        # 활채 반높이 (총 1.10m)
TIP_Y = 0.055                                       # 활채 끝의 앞쪽 치우침(리커브)
NOCK_D = 0.60                                       # `nock` 뼈 길이 = 크기 1일 때 당김

#: 시위 매듭의 당김 깊이(손잡이에서 뒤로, m) → `nock` 뼈 크기.
#:   `apex = GRIP + (TIP_Y - NOCK_D·s)·DIR`
BRACE, FULL, SNAP = 0.55, 1.033, 0.16
#   s=0.55 → 손잡이에서 0.28m (쉬는 자세 = **반쯤 당긴 채** 대기)
#   s=1.033 → 0.60m (만작)
#   s=0.16 → 0.041m (놓는 순간 시위가 앞으로 튀어 나간 자리)
# ★ 1차에는 `TIP_Y=0.15` 이라 브레이스 시위가 활채에서 28도나 벌어져,
#   화면에서 활을 가로지르는 **긴 사선**이 됐다(칼로 읽혔다). 실제 활은
#   시위가 활채와 거의 나란하다 — 지금 12도.


def _add(p, q, k=1.0):
    return (p[0] + q[0] * k, p[1] + q[1] * k, p[2] + q[2] * k)


def _sub(p, q):
    return (p[0] - q[0], p[1] - q[1], p[2] - q[2])


def _dot(p, q):
    return p[0] * q[0] + p[1] * q[1] + p[2] * q[2]


def _len(p):
    return math.sqrt(_dot(p, p))


def _unit(p):
    l = _len(p) or 1.0
    return (p[0] / l, p[1] / l, p[2] / l)


def nock_at(s: float):
    """시위 매듭의 자리(화면 좌표). `s` 는 `nock` 뼈의 y 크기다."""
    return _add(GRIP, DIR, TIP_Y - NOCK_D * s)


# ---------------------------------------------------------------- 두 뼈 역운동학
#: ★★ 활에서 새로 필요해진 것. 검은 「어깨를 몇 도 돌린다」로 끝나지만, 활은
#:   **손이 시위 매듭에 정확히 붙어 있어야** 한다 — 당김 깊이가 칸마다 달라지므로
#:   각도를 손으로 적으면 여섯 칸 중 다섯 칸에서 손이 시위를 놓친다.
#:   돌려주는 것은 (윗팔 방향, 아랫팔 방향) 둘 다 **화면 좌표**다.
def _ik2(root, target, l1, l2, pole):
    d = _sub(target, root)
    D = _len(d)
    D = min(max(D, abs(l1 - l2) + 1e-4), l1 + l2 - 1e-4)
    u = _unit(d)
    a = (l1 * l1 - l2 * l2 + D * D) / (2.0 * D)
    h = math.sqrt(max(0.0, l1 * l1 - a * a))
    # 팔꿈치가 향할 쪽 — u 에 수직인 성분만 남긴다
    p = _sub(pole, tuple(c * _dot(pole, u) for c in u))
    if _len(p) < 1e-6:
        p = (0.0, 0.0, 1.0)
    p = _unit(p)
    elbow = _add(_add(root, u, a), p, h)
    return _unit(_sub(elbow, root)), _unit(_sub(target, elbow)), elbow


# ---------------------------------------------------------------- 활과 관의 예산
#: ★★★ **이 캐릭터에서 가장 비싼 한 수** — 검사 11번(8방향 키 일관성 · 한도 2px)이
#:   활의 크기를 정한다. 요쿨에서는 후드 하나만 축에서 떼어 놓으면 됐는데, 활은
#:   **몸 축에서 멀리 떨어진 큰 소품**이라 결이 다르다.
#:
#:   화면 세로 = `world_y·sin20 + z·cos20` 이고, yaw 를 돌리면 한 점의 `world_y` 가
#:   **축에서의 수평 거리 r 만큼 진폭으로 흔들린다.** 그래서 그 점의 화면 높이가
#:   `±0.342·r` 만큼 오르내린다. 활채 끝은 r 이 0.6~0.8m 라 **±8~11px** 이다.
#:   실측(BOW_H 0.68 · GRIP a 0.55): 여덟 방향 키가 68~75px, **폭 7px**(한도 2px).
#:
#:   푸는 길은 하나뿐이다 — **어느 방향에서도 실루엣의 꼭대기가 관이게** 만든다.
#:   관은 축 위에 있어 거의 안 흔들리므로(r≈0.2 → ±2.7px), 관이 언제나 이기면
#:   키가 안 변한다. 요쿨의 후드가 하던 일과 같다.
#:     활채 끝의 화면 최대 = 0.9397·z_tip + 0.342·a_tip
#:                        = 0.9397·(1.347+0.970h) + 0.342·(g+0.053+0.242h)
#:     관 끝의 화면 최소   = 0.9397·z_ray - 0.342·r_ray
#:   두 식이 만나는 자리가 `0.994h + 0.342g <= 0.725`(관 꼭대기 z 2.19 기준)이고,
#:   그래서 **h 0.68 → 0.55 · g 0.55 → 0.42** 로 내렸다(원화의 활은 키의 68%인데
#:   여기서는 50%다 — 이것이 이 길이 실제로 치른 값이다).
#:
#:   ★ 그렇게 하면 이번에는 **세로가 칸을 넘는다**(관을 올린 만큼). 자락 반지름을
#:     0.72 → 0.60 으로 줄이고 `--zoom 0.94` 로 맞췄다. 셋이 한 예산을 나눠 쓴다:
#:     **관 높이 · 활 크기 · 자락 너비.**

# ---------------------------------------------------------------- 몸의 자
SH_Z = 1.52                     # 어깨 높이
SH_A = 0.245                    # 어깨 반너비 (화면 가로로 벌어진다 = 정면 몸통)
SH_D = 0.05
L_UP, L_FORE, L_HAND = 0.30, 0.28, 0.10

#: 팔꿈치가 향할 쪽. 활 팔은 아래·뒤로, 시위 팔은 위·뒤로 (실제 활쏘기 자세다)
POLE_BOW = (-0.30, 0.30, -0.92)
POLE_DRAW = (-0.95, 0.16, 0.28)

SH_BOW = (SH_A, SH_D, SH_Z)
SH_DRAW = (-SH_A, -SH_D, SH_Z)

#: 활 손이 잡는 쪽 — 손목에서 손잡이로 가는 방향
HAND_BOW_DIR = _unit((0.94, 0.0, -0.34))


def _bow_arm(grip=GRIP):
    """활 팔 — 손목이 손잡이 바로 뒤에 오게."""
    wrist = _add(grip, HAND_BOW_DIR, -L_HAND)
    up, fore, elbow = _ik2(SH_BOW, wrist, L_UP, L_FORE, POLE_BOW)
    return up, fore, HAND_BOW_DIR, wrist, elbow


def _draw_arm(s):
    """시위 팔 — 손목이 매듭 바로 뒤에 오게. `s` 가 곧 당김 깊이다."""
    apex = nock_at(s)
    hdir = _unit(_sub(apex, _add(SH_DRAW, (0, 0, 0.06))))
    wrist = _add(apex, hdir, -L_HAND)
    up, fore, elbow = _ik2(SH_DRAW, wrist, L_UP, L_FORE, POLE_DRAW)
    return up, fore, hdir, wrist, elbow


